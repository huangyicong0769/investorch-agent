function repositoryUrl(repository) {
  if (typeof repository === 'string') return repository
  if (repository && typeof repository.url === 'string') return repository.url
  return null
}

function normalizeLineEndings(text) {
  return text.replace(/\r\n?/g, '\n')
}

async function packageNotice(packagePath, lockMetadata) {
  const directory = resolve(frontendDirectory, packagePath)
  const packageMetadata = JSON.parse(await readFile(resolve(directory, 'package.json'), 'utf8'))
  const identity = `${packageMetadata.name}@${packageMetadata.version}`
  const licenseFiles = (await readdir(directory)).filter((name) => licenseFilePattern.test(name)).sort()
  let licenseText

  if (licenseFiles.length > 0) {
    const documents = await Promise.all(
      licenseFiles.map(async (name) => {
        const text = normalizeLineEndings(await readFile(resolve(directory, name), 'utf8'))
        return `${name}\n${text}`
      }),
    )
    licenseText = documents.join('\n\n')
  } else {
    licenseText = fallbackLicenses.get(identity)
    if (!licenseText) throw new Error(`No license document or audited fallback for ${identity}`)
  }

  const repository = repositoryUrl(packageMetadata.repository)
  return {
    identity,
    license: packageMetadata.license ?? lockMetadata.license ?? 'UNKNOWN',
    packagePath,
    repository,
    text: licenseText.trim(),
  }
}

function renderNotice(notice) {
  const metadata = [notice.identity, `Installed path: ${notice.packagePath}`, `License: ${notice.license}`]
  if (notice.repository) metadata.push(`Repository: ${notice.repository}`)

  return `${'='.repeat(80)}\n${metadata.join('\n')}\n${'-'.repeat(80)}\n${notice.text}`
}

const lock = JSON.parse(await readFile(lockPath, 'utf8'))
const productionPackages = Object.entries(lock.packages)
  .filter(([packagePath, metadata]) => packagePath.startsWith('node_modules/') && metadata.dev !== true)
  .sort(([left], [right]) => left.localeCompare(right))
const notices = await Promise.all(
  productionPackages.map(([packagePath, metadata]) => packageNotice(packagePath, metadata)),
)
const content = `InvestOrch Agent Web client third-party licenses

Generated from frontend/package-lock.json. Do not edit this file manually.
This file covers npm packages present in the production dependency graph.

${notices.map(renderNotice).join('\n\n')}\n`

if (checkOnly) {
  const existing = await readFile(outputPath, 'utf8')
  if (existing !== content) throw new Error('THIRD_PARTY_LICENSES.txt is out of date; run npm run licenses')
} else {
  await mkdir(dirname(outputPath), { recursive: true })
  await writeFile(outputPath, content, 'utf8')
}
