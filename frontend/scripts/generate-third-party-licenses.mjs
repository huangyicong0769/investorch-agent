const lockPath = resolve(frontendDirectory, 'package-lock.json')
const outputPath = resolve(frontendDirectory, '../src/investorch/web/static/THIRD_PARTY_LICENSES.txt')
const checkOnly = argv.includes('--check')
const licenseFilePattern = /^(licen[cs]e|copying|notice)(\..*)?$/i

